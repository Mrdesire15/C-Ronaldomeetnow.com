export const getSpfRecord = (domain: string, provider: RelayProvider): DnsRecord => {
  let include = '_spf.mx.cloudflare.net';
  if (provider === 'resend') {
    include = '_spf.mx.cloudflare.net include:resend.com';
  } else if (provider === 'brevo') {
    include = '_spf.mx.cloudflare.net include:spf.brevo.com';
  } else if (provider === 'smtp') {
    include = '_spf.mx.cloudflare.net';
  }

  return {
    type: 'TXT',
    name: '@',
    value: `v=spf1 include:${include} ~all`,
    purpose: 'SPF Authentication',
  };
};

export const getDkimRecord = (domain: string, provider: RelayProvider): DnsRecord => {
  if (provider === 'resend') {
    return {
      type: 'TXT',
      name: 'resend._domainkey',
      value: `p=MIGfMA0GCSqGSIb3DQEBAQUAA4GNADCBiQKBgQC3... (Auto-generated by Resend Dashboard)`,
      purpose: 'DKIM Signature',
    };
  }
  if (provider === 'brevo') {
    return {
      type: 'TXT',
      name: 'mail._domainkey',
      value: `k=rsa; p=MIGfMA0GCSqGSIb3DQEBAQUAA4GNADCBiQKBgQD... (Auto-generated by Brevo Dashboard)`,
      purpose: 'DKIM Signature',
    };
  }
  return {
    type: 'TXT',
    name: 'default._domainkey',
    value: `v=DKIM1; k=rsa; p=...`,
    purpose: 'DKIM Signature',
  };
};

export const getDmarcRecord = (domain: string): DnsRecord => ({
  type: 'TXT',
  name: '_dmarc',
  value: `v=DMARC1; p=none; rua=mailto:dmarc-reports@${domain || 'yourdomain.com'}`,
  purpose: 'DMARC Policy',
});

